module.exports=async function autoBuildBrowser(){
    const checks=[],assert=(v,label)=>{if(!v)throw new Error(label);checks.push(label);};
    const node=s=>{const n=document.querySelector(s);if(!n)throw new Error('Missing '+s);return n;};
    const settle=async()=>{await StarlightMotion.whenIdle();await new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)));};
    const click=async s=>{node(s).click();await settle();};
    const input=(s,value)=>{node(s).value=value;node(s).dispatchEvent(new Event('input',{bubbles:true}));};
    const read=()=>window.__qaReadState(),work=s=>s.agents.find(a=>a.id==='ui-story');
    const wait=async fn=>{for(let i=0;i<200;i++){if(await fn())return;await new Promise(r=>setTimeout(r,30));}throw new Error('Auto build timed out');};
    const beforeFetch=window.fetch,beforeConfirm=window.confirm;const requests=[];let mode='normal';
    try{
        window.confirm=()=>true;
        await click('#btnHamburger');await click('[data-home-tab="story"]');await click('#homeStoryList [data-work-id="ui-story"]');
        const before=await read(),count=work(before).conversations.length,rooms=JSON.stringify(before.rooms);
        window.fetch=async(url,options)=>{
            if(new URL(url,location.href).hostname!=='api.deepseek.com')return beforeFetch(url,options);
            const body=JSON.parse(options.body);requests.push(body);
            const last=body.messages.findLast(m=>m.role==='user')?.content||'',number=last.match(/自动构筑 · 第(\d+)章/)?.[1]||'200';
            const content='第'+number+'章 清晨\n\n「早呀！」\n\n小夏把书包放在窗边，两人继续昨天的话题。';
            const frame=text=>'data: '+JSON.stringify({choices:[{delta:{content:text}}]})+'\n\n';
            if(mode==='hold')return new Response(new ReadableStream({start(c){c.enqueue(new TextEncoder().encode(frame('已经收到的中断片段。')));}}));
            if(mode==='network')return new Response(frame('断网前的正文片段。'));
            const reason=mode==='resource'?'insufficient_system_resource':mode==='length'?'length':'stop';
            return new Response(frame(content)+'data: '+JSON.stringify({choices:[{delta:{},finish_reason:reason}],usage:{prompt_tokens:200,completion_tokens:100}})+'\n\ndata: [DONE]\n\n');
        };
        input('#messageInput','这是要保留的手动输入草稿');
        await click('#btnAutoBuildSettings');
        assert(!document.activeElement?.matches('input,textarea'),'打开构筑设置不自动弹键盘');
        input('#autoTargetMax','60000');await click('#autoSaveSettings');assert(StarlightMotion.isOpen(node('#autoBuildSettings'))&&requests.length===0,'超预算目标在保存前阻止，不发送失败请求');
        input('#autoNextNumber','200');input('#autoTargetMin','800');input('#autoTargetMax','1200');input('#autoNotes','保持自然日常，不揭晓秘密');input('#autoNextNote','本章先归还钥匙');
        await click('#autoSaveSettings');assert(requests.length===0,'保存设置不调用API');
        node('#btnAutoBuild').click();node('#btnAutoBuild').click();await settle();
        await wait(async()=>work(await read()).autoBuild?.mode==='awaiting');
        let state=work(await read());
        assert(requests.length===1,'连点自动构筑仍只有一次正文请求');assert(state.conversations.length===count+2,'本章任务和完整正文一同保存');
        assert(state.conversations.at(-2).kind==='autoTask'&&state.conversations.at(-1).chapterNumber===200,'任务来源和独立章号持久化');
        assert(node('#inputArea').hidden&&node('#inputArea').inert&&!node('#autoBuildBar').hidden,'章末确认与输入框互斥');
        assert(node('#autoBuildContinue')&&node('#autoBuildPause'),'完成后仅等待继续或暂停');
        assert(requests[0].messages.at(-1).content.includes('本章先归还钥匙'),'下一章要求参与生成');
        assert(!requests[0].messages.some(m=>/单拍推进|本轮许可/.test(m.content)),'自动长篇没有房间单拍限制');
        assert(state.draft==='这是要保留的手动输入草稿','进入自动构筑保留输入草稿');
        assert(!StarlightInspiration.selectExamples(state.conversations).some(e=>e.content.includes('【自动构筑')),'自动任务不参与用户写法学习');
        await new Promise(r=>setTimeout(r,100));assert(requests.length===1,'章末不会自动连写');
        await click('#autoBuildContinue');await wait(async()=>work(await read()).autoBuild?.nextNumber===202);
        assert(requests.length===2,'继续只增加一章一次正文请求');assert(!requests.at(-1).messages.at(-1).content.includes('本章先归还钥匙'),'一次性要求不重复用于下一章');
        await click('#autoBuildPause');assert(!node('#inputArea').hidden&&node('#messageInput').value.includes('手动输入草稿'),'暂停恢复原输入草稿');
        const complete=work(await read()).conversations.at(-1).content;
        mode='hold';node('#messagesContainer [data-message-index]:last-child').dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true}));await settle();await click('[data-message-action="regenerate"]');
        await wait(()=>requests.length===3&&node('#btnSend').classList.contains('stop-mode'));
        assert(work(await read()).conversations.at(-1).content===complete,'重生成等待期间原正文仍在数据库');
        await click('#btnSend');await wait(()=>!node('#btnSend').classList.contains('stop-mode'));await wait(async()=>!!work(await read()).incompleteDraft?.text.includes('中断片段'));
        assert(work(await read()).conversations.at(-1).content===complete,'停止重生成保持原章');
        mode='resource';await click('#btnAutoBuild');await wait(async()=>work(await read()).autoBuild?.mode==='paused'&&requests.length===4);
        assert(work(await read()).conversations.length===count+4&&work(await read()).autoBuild.nextNumber===202,'服务端资源中断不入正式历史也不跳章');
        mode='network';await click('#btnAutoBuild');await wait(async()=>work(await read()).incompleteDraft?.text==='断网前的正文片段。');
        assert(work(await read()).conversations.length===count+4,'断网片段不污染正文');
        mode='hold';await click('#btnAutoBuild');await wait(()=>!!document.querySelector('#autoBuildStop'));
        await click('#autoBuildStop');await wait(async()=>work(await read()).autoBuild?.mode==='paused');
        assert(work(await read()).autoBuild.nextNumber===202,'主动停止自动章不跳号');
        mode='normal';await click('#btnAutoBuild');await wait(async()=>work(await read()).autoBuild?.mode==='awaiting');
        assert(work(await read()).conversations.at(-1).chapterNumber===202,'再次启动从正确章号续写');
        await click('#autoBuildGear');
        await click('[data-auto-close]');
        const backup=StarlightArchive.createBackup(await read(),{mode:'story',id:'ui-story'});
        assert(backup.state.agents[0].autoBuild.nextNumber===203,'作品备份保留构筑进度与设置');
        assert(JSON.stringify((await read()).rooms)===rooms,'自动构筑不修改房间数据');
        assert(window.StarlightBack()===true&&!node('#inputArea').hidden,'系统返回退出章末等待并恢复手动输入');
        await wait(async()=>work(await read()).autoBuild?.mode==='paused');
        await click('#btnAutoBuild');await wait(async()=>work(await read()).autoBuild?.nextNumber===204);
        assert(!node('#autoBuildBar').hidden,'自动构筑可在人工暂停后再次进入章末确认');
        return {checks:checks.length};
    }finally{window.fetch=beforeFetch;window.confirm=beforeConfirm;}
};
